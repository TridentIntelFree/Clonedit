/* BUILD THE ONE-FILE AGENT CONNECTOR.

   agent/src/connector.mjs + mcp/tools.mjs + the MP3 encoder, bundled into
   agent/jbh88-agent.mjs: the file a person downloads from the app and points
   their agent's MCP config at. It must need nothing but Node, because the
   whole reason it exists is that the old route needed a clone and an
   `npm install` of this repository.

   Committed, like index.html, because pushing to main IS the deploy and the
   site serves the repository as it stands. tests/agent-connector.test.mjs
   rebuilds it in memory and fails when the committed copy has drifted.

   UNMINIFIED ON PURPOSE. The encoder is LAME (lamejs, LGPL-3.0). Shipped as
   readable source with its notice, the bundle is its own corresponding
   source and anyone can swap the library section for another build.

     node scripts/build-agent.mjs          write it
     node scripts/build-agent.mjs --check  exit 1 if the committed copy is stale */
import { build } from 'esbuild';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const OUT = resolve(root, 'agent/jbh88-agent.mjs');

export async function bundleAgent() {
  const r = await build({
    entryPoints: [resolve(root, 'agent/src/connector.mjs')],
    bundle: true, write: false, platform: 'node', format: 'esm', target: 'node18',
    legalComments: 'inline', minify: false, charset: 'utf8',
    banner: { js: [
      '/* JBH-88 agent connector — GENERATED by scripts/build-agent.mjs from',
      '   agent/src/connector.mjs and mcp/tools.mjs. Do not edit; edit those.',
      '',
      '   Run:   node jbh88-agent.mjs        (Node 18 or newer, nothing to install)',
      '   MCP:   {"mcpServers":{"jbh88":{"command":"node","args":["/full/path/to/jbh88-agent.mjs"]}}}',
      '',
      '   Contains lamejs (https://github.com/zhuker/lamejs, LAME https://lame.sourceforge.io),',
      '   licensed LGPL-3.0, unmodified and unminified below. */',
    ].join('\n') },
  });
  let js = r.outputFiles[0].text;
  /* the hashbang must be the very first bytes, ahead of the banner */
  js = js.replace(/^(\/\*[\s\S]*?\*\/\n)#!\/usr\/bin\/env node\n/, '#!/usr/bin/env node\n$1');
  return js;
}

if (import.meta.url === 'file://' + process.argv[1] || process.argv[1] && process.argv[1].endsWith('build-agent.mjs')) {
  const js = await bundleAgent();
  if (process.argv.includes('--check')) {
    const have = existsSync(OUT) ? readFileSync(OUT, 'utf8') : '';
    if (have !== js) {
      console.error('agent/jbh88-agent.mjs is stale — run node scripts/build-agent.mjs');
      process.exit(1);
    }
    console.log('agent/jbh88-agent.mjs is current (' + (js.length / 1024).toFixed(0) + ' KB)');
  } else {
    writeFileSync(OUT, js);
    console.log('wrote agent/jbh88-agent.mjs (' + (js.length / 1024).toFixed(0) + ' KB)');
  }
}
