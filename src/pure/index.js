export * from './pattern.js';
export * from './euclid.js';
export * from './scale.js';
export * from './groove.js';
export * from './morph.js';
export * from './poly.js';
export * from './ir.js';
export * from './install.js';
export * from './sfz.js';
/* what a sample can actually do — attack, ring, and whether a part is
   playable on it at a given tempo. Pure maths over a channel of audio,
   so it is tested in Node against signals whose answers are known. */
export * from './timbre.js';
/* WHAT IS ON THIS PAD — level, envelope, and the spectrum timbre.js
   does not measure. The song builder assigned kick, snare and hat by
   PAD INDEX, so a hat on A01 got the kick figure and every check in the
   repo passed. Identity is spectral and nothing here was looking. */
export * from './padprofile.js';
/* THE TRANSLATOR AT THE UI BOUNDARY. A `says` string serves an agent
   over MCP, which can call slot("kick", 0), and a person in a panel,
   who cannot. This swaps the call for the control that does it and
   explains a measurement term once, leaving every other word alone. */
export * from './plain.js';
/* WHERE MELODIC NOTES FALL AND HOW LONG THEY ARE, measured from 78,556
   Essen bars by scripts/study-cells.py. The rhythm cell library was
   hand-authored and was the last unmeasured thing in the write path.
   Placement and duration together, because separately they mean
   nothing. */
export * from './cells.js';
/* THE MEAN SPECTRUM OF EACH JOB, measured from a labelled pack by
   scripts/study-role-shapes.mjs. ROLE_TARGETS recognises a sound with
   two numbers, which cannot specify nine bands — making one needs
   something to aim at. */
export * from './roleshapes.js';
/* EQ-MATCHING A SAMPLE INTO A JOB, by changing the audio. The knob
   search was the obvious mechanism and measured 0% on a ride aimed at a
   kick, over 15 candidates: a filter cannot add low end nobody
   recorded. */
export * from './bend.js';
/* what a RECORDED take did: onsets off the buffer, timing against the
   grid, and the three faults that make a take unusable. The schedule
   checks next door cannot see a take at all -- they read the sequencer,
   and a take is audio off the mic bus. */
export * from './take.js';
/* WHAT NOTE THAT WAS. The app could hear level, bands, onsets, attack
   and ring, and could not tell you what you played -- so melody(),
   motif(), counterpoint() and harmony(), all calibrated against real
   corpora, could only ever read steps the sequencer scheduled. This is
   the bridge from audio to notes, and it is monophonic and says so. */
export * from './pitch.js';
/* HOW FAST IS THIS. Nothing here could answer that: pulse() measures
   whether a beat can be found at a tempo the app already set, and says
   nothing about a recording that arrived with a tempo of its own. */
export * from './tempo.js';
/* DOES THE PIECE HAVE A SHAPE. Every other check looks inside a
   pattern; this looks at the chain of them, which AGENTS.md records as
   measurable only outside the app from exported MIDI. */
export * from './form.js';
/* recipes: slots with a measurable brief, and a seeded generator */
export * from './recipes.js';
